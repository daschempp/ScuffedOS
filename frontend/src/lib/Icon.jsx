/* Scuffed OS — Lucide icon wrapper.
   The prototype referenced Lucide icons by kebab-case string name (e.g.
   <Icon name="circle-check-big" />). We keep that ergonomic API but back it with
   the `lucide-react` package: an explicit name→component map so every icon is
   statically imported (tree-shaken, no runtime/lazy flash). Sizing/coloring is
   driven by kit.css (`.parent svg { width: … }`, `color: …` via currentColor),
   exactly as in the design system. */
