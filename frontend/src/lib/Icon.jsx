export function Icon({ name, size, ...rest }) {
  const Cmp = ICONS[name]
  if (!Cmp) {
    if (import.meta.env.DEV) console.warn(`[Icon] unknown icon "${name}"`)
    return null
  }
  return <Cmp {...(size != null ? { size } : {})} {...rest} />
}
